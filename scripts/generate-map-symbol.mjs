import ms from 'milsymbol';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { format } from 'prettier';
const version = JSON.parse(readFileSync('node_modules/milsymbol/package.json', 'utf8')).version;
const license = readFileSync('node_modules/milsymbol/LICENSE', 'utf8');
const svg = new ms.Symbol('130310001412110000000000000000', { size: 32 }).asSVG();
if (
  !svg.includes('<svg') ||
  /<script|<foreignObject|onload=|https?:\/\/[^w]/i.test(
    svg.replace('http://www.w3.org/2000/svg', ''),
  )
)
  throw new Error('Unexpected generated symbol content.');
mkdirSync('public/maps', { recursive: true });
writeFileSync('public/maps/friendly-unit.svg', svg);
writeFileSync('public/maps/LICENSE.milsymbol.txt', license);
writeFileSync(
  'lib/tactical-symbol.ts',
  await format(
    `// Generated by scripts/generate-map-symbol.mjs using MIT-licensed milsymbol ${version}.\nexport const unitSvg = ${JSON.stringify(svg)};\nexport const symbolLicense = ${JSON.stringify(license)};\nexport const symbolVersion = ${JSON.stringify(version)};\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 96 },
  ),
);
console.log(`Generated friendly infantry symbol with milsymbol ${version}.`);
